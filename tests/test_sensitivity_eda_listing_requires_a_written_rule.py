"""The sensitivity master lists a `plots/eda/` figure only when it writes that figure's rule.

The sensitivity-master Snakefile generator writes the in-report EDA plot rules through
the reporting-set dispatcher, which skips a selection whose predicate is false. It then
lists the EDA figures in `rule all` and in `render_report`'s inputs under a separate
condition. For the `b4b` set the rule predicate is `has_preserved_raw_outputs`, which is
false under `clear_raw: all`, so the rules are not written. A figure listed without a
rule is an output Snakemake must produce and cannot, so the workflow fails at DAG build
on a tree that lacks it.

The Snakefile is generated by the real generator on a builder made without `__init__`.
The analysis configs are built with `model_construct`, there is one member with one
event, and every plot builder other than the EDA one is replaced by one that writes
nothing. No analysis is constructed, no solver runs and no Snakemake process starts.
"""

