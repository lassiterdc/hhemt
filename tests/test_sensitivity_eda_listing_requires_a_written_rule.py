import re
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import MagicMock

import pandas as pd
import pytest

from hhemt.config.analysis import analysis_config
from hhemt.config.eda import eda_config
from hhemt.config.report import DEFAULT_REPORT_CONFIG, report_config
from hhemt.config.system import system_config
from hhemt.report_renderers._reporting_sets import get_reporting_set
from hhemt.workflow import RuleEmissionContext, SensitivityAnalysisWorkflowBuilder

_QUIET_BUILDERS = (
    "system_overview",
    "per_sim",
    "per_analysis_summary",
    "scenario_status_appendix",
    "errors_and_warnings",
    "disk_utilization",
    "metadata",
    "workflow_performance",
)


def _b4b_master_snakefile(tmp_path: Path, clear_raw: str) -> str:
    """Generate the b4b sensitivity-master Snakefile for a one-member, one-event stand-in."""
    report = report_config.model_validate({**DEFAULT_REPORT_CONFIG.model_dump(), "reporting_set": "b4b"})
    cfg_analysis = analysis_config.model_construct(
        report=report,
        eda=eda_config(),
        clear_raw=clear_raw,
        toggle_sensitivity_analysis=True,
        analysis_id="b4b-listing",
        multi_sim_run_method="local",
        process_in_sim_rule=False,
    )
    experiment = MagicMock()
    experiment.cfg_analysis = cfg_analysis
    experiment._active_reporting_set = get_reporting_set("b4b")
    experiment._cfg_report = report
    experiment.analysis_paths.analysis_dir = tmp_path
    experiment.analysis_paths.analysis_log_directory = tmp_path / "logs"
    experiment._get_enabled_model_types = lambda: ["tritonswmm"]

    builder = object.__new__(SensitivityAnalysisWorkflowBuilder)
    builder.experiment = experiment
    builder.system = SimpleNamespace(
        cfg_system=system_config.model_construct(
            toggle_triton_model=False, toggle_tritonswmm_model=True, toggle_swmm_model=False
        )
    )
    member = SimpleNamespace(
        cfg_analysis=analysis_config.model_construct(
            run_mode="serial",
            n_mpi_procs=1,
            n_omp_threads=1,
            n_gpus=0,
            n_nodes=1,
            hpc_time_min_per_sim=30,
            mem_gb_per_cpu=2,
            clear_raw=clear_raw,
        ),
        cfg_hpc_system=None,
        analysis_config_yaml=tmp_path / "member0.yaml",
        _system=SimpleNamespace(system_config_yaml=tmp_path / "system.yaml"),
        df_sims=pd.DataFrame(index=[0]),
        _retrieve_weather_indexer_using_integer_index=lambda i: {"event_id": i},
        analysis_paths=SimpleNamespace(analysis_dir=tmp_path / "members" / "member_0"),
    )
    builder.sensitivity_analysis = MagicMock()
    builder.sensitivity_analysis.members = {"0": member}
    builder.sensitivity_analysis.independent_vars = []
    builder.sensitivity_analysis.member_prefix = "member"
    builder.sensitivity_analysis._write_member_id_fingerprint = lambda *_a, **_kw: None
    builder.unique_system_targets = [
        SimpleNamespace(
            target_id=0, analysis_ids=["0"], system_config_yaml=tmp_path / "system.yaml", target_partition=None
        )
    ]
    builder.python_executable = "python"
    builder._container_process_prefix = ""
    builder._process_python_executable = "python"
    base = MagicMock()
    for name in (
        "_build_resource_block",
        "_get_config_args",
        "_get_conda_env_path",
        "_emit_wait_for_sim_rule_block",
        "_build_export_scenario_status_rule",
    ):
        getattr(base, name).return_value = ""
    for name in _QUIET_BUILDERS:
        getattr(base, f"_build_plot_rule_block_{name}").return_value = ""
    base._get_report_cfg_static_backend.return_value = "plotly"
    base._resolve_gpu_alloc_mode.return_value = "gres"
    base._resolved_simulate_retries.return_value = 0
    base._resolved_execution_locus = None
    base._make_rule_emission_context.return_value = RuleEmissionContext(
        python_executable="python",
        log_dir_rel="_logs",
        conda_env_path="",
        config_args_str="--system-config s.yaml --analysis-config a.yaml",
        is_sensitivity=True,
        static_backend="plotly",
    )
    builder._base_builder = base
    builder._build_plot_rule_block_per_sim_per_member = lambda **_kw: ""
    builder._build_plot_rule_block_sensitivity_benchmarking = lambda *_a, **_kw: ""
    return builder.generate_master_snakefile_content(which="both", compression_level=5)


def _eda_paths(text: str) -> set[str]:
    return set(re.findall(r'"(plots/eda/[^"]+)"', text))


def _rule_body(content: str, name: str) -> str:
    match = re.search(rf"^rule {name}:\n(.*?)(?=^rule |\Z)", content, re.M | re.S)
    return match.group(1) if match else ""


def _written_eda_outputs(content: str) -> set[str]:
    """`plots/eda/` paths named in the `output:` block of an emitted rule."""
    written: set[str] = set()
    for match in re.finditer(r"^rule (\S+):\n(.*?)(?=^rule |\Z)", content, re.M | re.S):
        output = re.search(r"output:\s*(.*?)(?:\n\s{4}\w+:|\Z)", match.group(2), re.S)
        if output:
            written |= _eda_paths(output.group(1))
    return written


@pytest.mark.parametrize("clear_raw", ["all", "none"])
def test_b4b_master_lists_no_eda_figure_without_its_rule(tmp_path, clear_raw) -> None:
    """Every `plots/eda/` figure in `rule all` or `render_report` is an emitted rule's output.

    Property: in the b4b sensitivity-master Snakefile, the `plots/eda/` paths listed in
    `rule all` and in `render_report`'s inputs are a subset of the paths emitted rules
    write. With `clear_raw: all` the EDA rules are not written, so nothing under
    `plots/eda/` is listed; with `clear_raw: none` (the control) both figures are
    written and listed.
    Class: EDA selections whose predicate can be false while `eda.enabled_plots` is not
    empty, so the rule-writing check and the listing check disagree.
    Why: a listed output with no rule is one Snakemake must produce and cannot, so the
    workflow fails at DAG build on a tree that lacks the figure.
    What kills it: a listing condition that omits the EDA selection's predicate, as the
    generator's did, which lists both figures under `clear_raw: all`.
    Second correct implementation: filtering the listing by the emitted rules' outputs
    after emission, instead of re-evaluating the predicate, still passes.
    """
    content = _b4b_master_snakefile(tmp_path, clear_raw)
    written = _written_eda_outputs(content)
    listed = _eda_paths(_rule_body(content, "all")) | _eda_paths(_rule_body(content, "render_report"))

    assert listed <= written
    expected = set() if clear_raw == "all" else {"plots/eda/config_diff_maps.html", "plots/eda/raw_byte_identity.html"}
    assert listed == expected
