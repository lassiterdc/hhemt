"""Consolidated-zarr-only deletion runner for the SLURM-offloaded reprocess
delete (R8). Invoked by the analysis-level ``delete_reprocess_consolidation``
rule in ``Snakefile.reprocess_delete`` (the master dir for sensitivity, the
analysis dir for non-sensitivity). Under D-scope Option C the per-SUB
``analysis_datatree.zarr`` is deleted by ``delete_member_reprocess_runner``
(item 5b), NOT by this runner. Deletes the ``summary`` branches of
``analysis_datatree.zarr`` and (sensitivity master) ``sensitivity_datatree.zarr`` and
``experiment_datatree.zarr`` — the HEAVY component. The ``timeseries`` branches of
``analysis_datatree.zarr`` are KEPT: they are append-only and, with the clearing switch
on, the only copy of the series. The ``summary`` branches are KEPT too when any scenario records its per-scenario
summary stores as cleared. For that store the root consolidation stamp is removed
FIRST and the ``summary`` branches after it, so a kill part-way leaves a tree with no
stamp, which the next consolidation reads as incomplete and answers by rewriting every
``summary`` group in place. Does NOT touch report/plots/_status/_generated (regenerated by
the reprocess run).
Distinct from ``delete_consolidation_runner`` (whole analysis-level artifact set + _status)."""

from __future__ import annotations

import argparse
import datetime
import json
import logging
import os
import sys
from pathlib import Path

from hhemt.du_sentinels import delete_and_account
from hhemt.status_flags import write_status_flag
from hhemt.utils import (
    CONSOLIDATION_STAMP_ATTRS,
    EXPERIMENT_TREE_NAME,
    REGULAR_TREE_NAME,
    ROOT_TREE_NAMES,
    deferred_consolidation,
    update_zarr_root_attrs,
)

logger = logging.getLogger(__name__)

# NARROW set — ONLY the consolidated zarrs. Report/plots/_status are regenerated,
# never deleted here. These two filenames are the canonical defaults
# (analysis.py:160 computes analysis_paths.analysis_datatree_zarr from the same
# "analysis_datatree.zarr" literal; the sensitivity master sets
# the shared ROOT_TREE_NAMES tuple). Sourced from that tuple rather than hardcoded:
# the previous `KEEP IN SYNC` comment here did NOT prevent this list going stale
# against V0021, so the invariant is now carried by a single definition instead of
# by an instruction to remember.
_REPROCESS_ZARR_ARTIFACTS = list(ROOT_TREE_NAMES)


#: Where the ``summary`` branches sit in each tree that keeps its series: directly under ``{family}/{kind}`` in an
#: analysis tree, and under ``member_{id}/{family}/{kind}`` in the sensitivity master.
_SUMMARY_GLOBS = {REGULAR_TREE_NAME: "*/*/summary", EXPERIMENT_TREE_NAME: "*/*/*/summary"}


def records_summary_clearing(analysis_dir: Path) -> bool:
    """Whether any scenario under ``analysis_dir`` (or under its members) records its summary stores as cleared.

    Read path-only from ``sims/{event_id}/log_{model}.json`` and, for a sensitivity master, from
    ``members/*/sims/{event_id}/log_{model}.json``. A recorded clearing means the ``summary`` branch holds the only
    copy of that scenario's summaries, so deleting the branch would destroy them.
    """
    from hhemt.scenario_records import REMOVED_STATES
    from hhemt.summary_paths import SUMMARY_CLEARING_FIELD, parse_summary_clearing_record

    # Removed scenarios (D24 (e)) keep their model logs in the analysis-level record, so the guard that keeps every
    # summary branch reads the records too: after the directory removal the branch is the only copy, and a glob of
    # `sims/*/log_*.json` alone would find nothing and let the branches be deleted.
    for pattern in (
        "_status/scenario_records/*.json",
        "_status/member_records/member_*/scenario_records/*.json",
        "members/*/_status/scenario_records/*.json",
    ):
        for rec_file in Path(analysis_dir).glob(pattern):
            try:
                rec = json.loads(rec_file.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue
            if not isinstance(rec, dict) or rec.get("state") not in REMOVED_STATES:
                continue
            for logged in (rec.get("model_logs") or {}).values():
                if isinstance(logged, dict) and parse_summary_clearing_record(logged.get(SUMMARY_CLEARING_FIELD)):
                    return True
    for pattern in ("sims/*/log_*.json", "members/*/sims/*/log_*.json"):
        for log_file in Path(analysis_dir).glob(pattern):
            try:
                payload = json.loads(log_file.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue
            if isinstance(payload, dict) and parse_summary_clearing_record(payload.get(SUMMARY_CLEARING_FIELD)):
                return True
    return False


def delete_summary_branches(
    tree: Path, analysis_dir: Path, *, pattern: str = "*/*/summary", scope: str = "analysis"
) -> list[Path]:
    """Remove the root stamp, then every ``summary`` branch of ``tree`` matching ``pattern``; keep every other branch.

    When any scenario records its summary stores as cleared (``records_summary_clearing``), the ``summary`` branches
    are KEPT as well and only the root stamp is removed: the branch is then the only copy, and the next
    consolidation plans each event against it instead of rewriting the group.

    ``pattern`` is ``*/*/summary`` for an analysis tree (``{family}/{kind}/summary``) and ``*/*/*/summary`` for the
    sensitivity master (``member_{id}/{family}/{kind}/summary``); a master's ``parameters`` dataset and member nodes
    are not summary branches and stay. ``scope`` names the disk-use sentinel the deletion is accounted against:
    ``analysis`` for an analysis or master directory, ``member`` for a sensitivity member's directory.

    The stamp goes first (inside one ``deferred_consolidation`` block, so the zarr index is rebuilt once at the end),
    which is what makes an interruption recognisable: a tree without its stamp is read as incomplete. A branch is
    deleted whether or not its group document survives, because a kill inside an earlier delete can leave a directory
    whose ``zarr.json`` is gone. Returns the deleted paths, sorted.
    """
    removed: list[Path] = []
    keep_summaries = records_summary_clearing(analysis_dir)
    with deferred_consolidation(tree):
        update_zarr_root_attrs(tree, remove=CONSOLIDATION_STAMP_ATTRS)
        if keep_summaries:
            return removed
        for summary in sorted(p for p in tree.glob(pattern) if p.is_dir()):
            print(f"[delete-reprocess-zarr] removing {summary}", flush=True)
            delete_and_account([summary], scope_dir=analysis_dir, scope=scope)  # type: ignore[arg-type]
            removed.append(summary)
    return removed


def _parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--analysis-dir", type=Path, required=True)
    return parser.parse_args(argv)


def _write_submission_sentinel(sentinel_path: Path, *, rule_token: str, slurm_job_id: str) -> None:
    sentinel_path.parent.mkdir(parents=True, exist_ok=True)
    tmp = sentinel_path.with_suffix(".json.tmp")
    tmp.write_text(
        json.dumps(
            {
                "slurm_jobid": slurm_job_id,
                "run_uuid": os.environ.get("SLURM_JOB_NAME"),
                "rule_token": rule_token,
                "submitted_at": datetime.datetime.now().isoformat(),
            }
        )
    )
    os.replace(tmp, sentinel_path)


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv)
    analysis_dir = args.analysis_dir.resolve()
    _sentinel: Path | None = None
    _slurm_jobid = os.environ.get("SLURM_JOB_ID")
    if _slurm_jobid:
        _rule_token = "delete_reprocess_consolidation"
        _sentinel = analysis_dir / "_status" / "_submitted" / f"{_rule_token}.json"
        _write_submission_sentinel(_sentinel, rule_token=_rule_token, slurm_job_id=_slurm_jobid)
    try:
        for name in _REPROCESS_ZARR_ARTIFACTS:
            path = analysis_dir / name
            if not path.exists():
                continue
            if name in _SUMMARY_GLOBS:
                delete_summary_branches(path, analysis_dir, pattern=_SUMMARY_GLOBS[name])
                continue
            print(f"[delete-reprocess-zarr] removing {path}", flush=True)
            delete_and_account([path], scope_dir=analysis_dir, scope="analysis")
        flag_path = analysis_dir / "_status" / "_deleting_reprocess" / "reprocess_consolidation.flag"
        write_status_flag(flag_path, rule_name="delete_reprocess_consolidation")
        return 0
    finally:
        if _sentinel is not None:
            # EXEMPT-DU: status-flag
            _sentinel.unlink(missing_ok=True)


if __name__ == "__main__":
    sys.exit(main())
